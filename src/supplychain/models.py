class SupplierMessage(StrictBaseModel):
    """Message output by Supplier Liaison agent."""

    cycle_id: str
    sku_id: str
    warehouse_id: str
    supplier_id: str | None = None
    po_draft: PurchaseOrderDraft | None = None
    email: SupplierEmailDraft | None = None
    alternates_considered: list[str] = Field(default_factory=list)
    rationale: Annotated[str, Field(max_length=600)]
    confidence: Annotated[float, Field(ge=0.0, le=1.0)]

    @field_validator("cycle_id")
    @classmethod
    def validate_cycle(cls, v: str) -> str:
        return _check_strict_regex(v, CYCLE_ID_PATTERN, "cycle_id")

    @field_validator("sku_id")
    @classmethod
    def validate_sku(cls, v: str) -> str:
        return _check_strict_regex(v, SKU_ID_PATTERN, "sku_id")

    @field_validator("warehouse_id")
    @classmethod
    def validate_warehouse(cls, v: str) -> str:
        return _check_strict_regex(v, WAREHOUSE_ID_PATTERN, "warehouse_id")

    @field_validator("supplier_id")
    @classmethod
    def validate_supplier(cls, v: str | None) -> str | None:
        if v is not None:
            return _check_strict_regex(v, SUPPLIER_ID_PATTERN, "supplier_id")
        return v

    @field_validator("alternates_considered")
    @classmethod
    def validate_alternates(cls, v: list[str]) -> list[str]:
        for sup in v:
            _check_strict_regex(sup, SUPPLIER_ID_PATTERN, "alternates_considered")
        return v

    @model_validator(mode="after")
    def validate_order_consistency(self) -> SupplierMessage:
        if self.po_draft is not None:
            if self.supplier_id is None:
                raise ValueError("supplier_id is required when po_draft is present")
            if self.email is None:
                raise ValueError("email is required when po_draft is present")
            if self.po_draft.supplier_id != self.supplier_id:
                raise ValueError("po_draft.supplier_id must match supplier_id")
        return self


