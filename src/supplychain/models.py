"""Pydantic message schemas and contracts between agents and system components."""

from __future__ import annotations

import re
from datetime import date
from typing import Annotated, Any, Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
    model_validator,
)

# Strict regex definitions per SPEC 5 and 6
CYCLE_ID_PATTERN = r"CYC-[0-9]{8}-[0-9]{4}"
SKU_ID_PATTERN = r"SKU[0-9]{4}"
WAREHOUSE_ID_PATTERN = r"WH-[NSW]"
SUPPLIER_ID_PATTERN = r"SUP[0-9]{3}"
FINDING_CODE_PATTERN = r"QA[0-9]{2}"


def _check_strict_regex(val: str, pattern: str, name: str) -> str:
    if not isinstance(val, str) or not re.fullmatch(pattern, val):
        raise ValueError(f"Invalid {name} format: {val!r}")
    return val


class StrictBaseModel(BaseModel):
    """Base model forbidding extra fields and enforcing strict validation."""

    model_config = ConfigDict(
        extra="forbid",
        validate_assignment=True,
        str_strip_whitespace=False,
    )


class CycleRequest(StrictBaseModel):
    """Initial cycle trigger request."""

    scenario_id: Annotated[str, Field(min_length=1, max_length=50)]
    sku_id: str
    warehouse_id: str

    @field_validator("sku_id")
    @classmethod
    def validate_sku(cls, v: str) -> str:
        return _check_strict_regex(v, SKU_ID_PATTERN, "sku_id")

    @field_validator("warehouse_id")
    @classmethod
    def validate_warehouse(cls, v: str) -> str:
        return _check_strict_regex(v, WAREHOUSE_ID_PATTERN, "warehouse_id")


